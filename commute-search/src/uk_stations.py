def get_stations_within_distance(max_km: float = 100, center_lat: float = 51.5, center_lon: float = -0.1):
    """Get stations within a certain distance of a point"""
    import math

    def haversine(lat1, lon1, lat2, lon2):
        R = 6371
        dlat = math.radians(lat2 - lat1)
        dlon = math.radians(lon2 - lon1)
        a = math.sin(dlat/2)**2 + math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.sin(dlon/2)**2
        return R * 2 * math.atan2(math.sqrt(a), math.sqrt(1-a))

    return [(name, pc, lat, lon) for name, pc, lat, lon in UK_STATIONS
            if haversine(center_lat, center_lon, lat, lon) <= max_km]

